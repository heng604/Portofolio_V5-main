-- Portfolio V5 secure schema. Run in Supabase SQL Editor as project owner.
create extension if not exists pgcrypto;

create or replace function public.is_portfolio_admin()
returns boolean language sql stable security definer set search_path = public, auth as $$
  select lower(coalesce(auth.jwt() ->> 'email', '')) = lower('Seangheng2006@gmail.com');
$$;
revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to anon, authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null default 'user' check (role in ('admin','user')),
  created_at timestamptz not null default now()
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  "Title" text not null,
  "Description" text not null default '',
  "Img" text not null default '',
  "Link" text not null default '',
  "Github" text not null default '',
  "Features" jsonb not null default '[]'::jsonb,
  "TechStack" jsonb not null default '[]'::jsonb,
  slug text unique,
  is_published boolean not null default true,
  order_index integer not null default 0,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists projects_public_order_idx on public.projects (is_published, order_index, created_at desc);
create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  "Img" text not null,
  title text not null default '',
  issuer text not null default '',
  issued_at date,
  order_index integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.tech_stack (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null default 'Other',
  icon_url text not null default '',
  order_index integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.site_content (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.translations (
  translation_key text not null,
  language text not null check (language in ('en','km')),
  value text not null,
  updated_at timestamptz not null default now(),
  primary key (translation_key, language)
);
create table if not exists public.portfolio_comments (
  id uuid primary key default gen_random_uuid(), content text not null check (length(content) between 1 and 1500),
  user_name text not null check (length(user_name) between 1 and 100), profile_image text,
  is_pinned boolean not null default false, is_approved boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists portfolio_comments_public_idx on public.portfolio_comments (is_approved, is_pinned desc, created_at desc);
create table if not exists public.contact_submissions (
  id uuid primary key default gen_random_uuid(), name text not null, email text not null,
  subject text not null, message text not null, status text not null default 'received' check (status in ('received','read','replied','spam')),
  created_at timestamptz not null default now()
);
create index if not exists contact_submissions_created_idx on public.contact_submissions (created_at desc);
create table if not exists public.tip_payments (
  id text primary key, amount numeric(14,2) not null check (amount > 0), currency text not null check (currency in ('USD','KHR')),
  recipient_account_id text not null, recipient_name text not null, khqr_md5 text not null unique,
  transaction_hash text unique, from_account_id text, status text not null default 'pending' check (status in ('pending','success','expired','cancelled','failed')),
  mode text not null default 'sandbox' check (mode in ('sandbox','production','simulation')),
  expires_at timestamptz not null, verified_at timestamptz, created_at timestamptz not null default now()
);
create index if not exists tip_payments_status_created_idx on public.tip_payments (status, created_at desc);
create table if not exists public.website_settings (
  key text primary key, value jsonb not null default '{}'::jsonb, updated_at timestamptz not null default now()
);

