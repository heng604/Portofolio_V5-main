drop policy if exists "profiles own or admin read" on public.profiles;
create policy "profiles own or admin read" on public.profiles for select to authenticated using (id = auth.uid() or public.is_portfolio_admin());
drop policy if exists "admin manages profiles" on public.profiles;
create policy "admin manages profiles" on public.profiles for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin());

do $$ declare t text; begin
  foreach t in array array['projects','certificates','tech_stack'] loop
    execute format('drop policy if exists "public read published %1$s" on public.%1$s', t);
    execute format('create policy "public read published %1$s" on public.%1$s for select to anon, authenticated using (is_published = true or public.is_portfolio_admin())', t);
    execute format('drop policy if exists "admin writes %1$s" on public.%1$s', t);
    execute format('create policy "admin writes %1$s" on public.%1$s for all to authenticated using (public.is_portfolio_admin()) with check (public.is_portfolio_admin())', t);
  end loop;
end $$;
